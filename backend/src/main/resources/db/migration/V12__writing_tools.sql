-- 글쓰기 도구: 연재, 임시 저장·예약 발행 (specs/013 data-model, ERD-변경-요청.md E-10)
-- 글 표(post)는 바꾸지 않는다: 임시 저장·예약 글은 따로 표에 두어 공개 글을 읽는 쿼리가 그대로다 (D-1, D-2)

-- 연재 (D-9, D-11)
CREATE TABLE series (
    series_id   BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    blog_id     BIGINT       NOT NULL,
    name        VARCHAR(30)  NOT NULL,
    description VARCHAR(200) NOT NULL DEFAULT '',
    created_at  TIMESTAMPTZ  NOT NULL,
    CONSTRAINT series_pk PRIMARY KEY (series_id),
    CONSTRAINT fk_series_blog FOREIGN KEY (blog_id) REFERENCES blog (blog_id)
);

CREATE INDEX idx_series_blog ON series (blog_id, created_at);

-- 연재에 든 글: 글 하나는 연재 하나에만 (post_id 고유). 화 번호는 저장하지 않는다 (D-10)
CREATE TABLE series_post (
    series_id  BIGINT  NOT NULL,
    post_id    BIGINT  NOT NULL,
    sort_order INTEGER NOT NULL,
    CONSTRAINT series_post_pk PRIMARY KEY (series_id, post_id),
    CONSTRAINT uk_series_post_post UNIQUE (post_id),
    CONSTRAINT fk_series_post_series FOREIGN KEY (series_id) REFERENCES series (series_id) ON DELETE CASCADE,
    CONSTRAINT fk_series_post_post FOREIGN KEY (post_id) REFERENCES post (post_id)
);

CREATE INDEX idx_series_post_order ON series_post (series_id, sort_order);

-- 임시 저장·예약 글 (D-1 ~ D-4). publish_at이 비어 있으면 임시 저장, 있으면 예약
CREATE TABLE post_draft (
    post_draft_id BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    blog_id       BIGINT       NOT NULL,
    category_id   BIGINT,
    topic_id      BIGINT,
    series_id     BIGINT,
    title         VARCHAR(100) NOT NULL DEFAULT '',
    content       TEXT         NOT NULL DEFAULT '',
    visibility    VARCHAR(10)  NOT NULL DEFAULT 'public',
    tags          VARCHAR(200) NOT NULL DEFAULT '',
    publish_at    TIMESTAMPTZ,
    request_key   VARCHAR(36)  NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL,
    updated_at    TIMESTAMPTZ  NOT NULL,
    CONSTRAINT post_draft_pk PRIMARY KEY (post_draft_id),
    CONSTRAINT uk_post_draft_request_key UNIQUE (request_key),
    CONSTRAINT ck_post_draft_visibility CHECK (visibility IN ('public', 'private')),
    CONSTRAINT fk_post_draft_blog FOREIGN KEY (blog_id) REFERENCES blog (blog_id),
    CONSTRAINT fk_post_draft_category FOREIGN KEY (category_id) REFERENCES category (category_id) ON DELETE SET NULL,
    CONSTRAINT fk_post_draft_topic FOREIGN KEY (topic_id) REFERENCES topic (topic_id),
    CONSTRAINT fk_post_draft_series FOREIGN KEY (series_id) REFERENCES series (series_id) ON DELETE SET NULL
);

CREATE INDEX idx_post_draft_blog ON post_draft (blog_id, updated_at DESC);
CREATE INDEX idx_post_draft_publish_at ON post_draft (publish_at) WHERE publish_at IS NOT NULL;

-- 임시 저장 글의 이미지 (D-8). 정리 작업은 글에도 임시 저장 글에도 연결되지 않은 것만 지운다
ALTER TABLE post_image ADD COLUMN post_draft_id BIGINT;
ALTER TABLE post_image ADD CONSTRAINT fk_post_image_post_draft
    FOREIGN KEY (post_draft_id) REFERENCES post_draft (post_draft_id) ON DELETE SET NULL;
DROP INDEX idx_post_image_unlinked;
CREATE INDEX idx_post_image_unlinked ON post_image (users_id, created_at)
    WHERE post_id IS NULL AND post_draft_id IS NULL;
CREATE INDEX idx_post_image_post_draft_id ON post_image (post_draft_id);

COMMENT ON TABLE series IS '연재';
COMMENT ON TABLE series_post IS '연재에 든 글';
COMMENT ON TABLE post_draft IS '임시 저장·예약 글';
COMMENT ON COLUMN post_draft.publish_at IS '예약 발행 시각 (비어 있으면 임시 저장)';
COMMENT ON COLUMN post_image.post_draft_id IS '임시 저장 글 (본문에 든 이미지)';
