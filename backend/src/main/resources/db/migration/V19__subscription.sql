-- 구독·알림 (specs/016 data-model, ERD E-13).
--   blog_subscription: 원고 받아 보기(블로그 구독). 한 사람이 한 블로그에 한 줄, 원고 편지(메일)도 받을지.
--   notification: 우편함 소식(받아 보는 블로그의 새 글, 내 글에 달린 댓글). 30일 뒤 서버가 지운다.
--   post.first_published_at: 글이 처음 공개된 시각. 비어 있는 글이 공개될 때만 채우고 새 글 소식을 낸다(두 번 내지 않게).
-- 탈퇴(MemberWithdrawnEvent)·블로그 닫기(BlogClosingEvent) 때 subscription 모듈이 먼저 지운다. 회원·블로그 줄을 실제로 지우는 일은
-- 서비스에 없지만(회원은 남는 soft delete), 연쇄 삭제를 걸어 두어 소식을 만드는 일꾼과 지우기가 겹쳐도 막히지 않는다.
-- 글이 지워지면 소식은 남기고 글 번호만 비운다(ON DELETE SET NULL, 그때의 제목은 남는다).

ALTER TABLE post ADD COLUMN first_published_at TIMESTAMPTZ;
UPDATE post SET first_published_at = created_at WHERE visibility = 'public';
COMMENT ON COLUMN post.first_published_at IS '처음 공개된 시각 (새 글 소식은 이때 한 번만)';

CREATE TABLE blog_subscription (
    blog_subscription_id BIGINT      NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    users_id             BIGINT      NOT NULL,
    blog_id              BIGINT      NOT NULL,
    email_enabled        BOOLEAN     NOT NULL DEFAULT false,
    created_at           TIMESTAMPTZ NOT NULL,
    CONSTRAINT blog_subscription_pk PRIMARY KEY (blog_subscription_id),
    CONSTRAINT uk_blog_subscription_users_blog UNIQUE (users_id, blog_id),
    CONSTRAINT fk_blog_subscription_users FOREIGN KEY (users_id) REFERENCES users (users_id) ON DELETE CASCADE,
    CONSTRAINT fk_blog_subscription_blog FOREIGN KEY (blog_id) REFERENCES blog (blog_id) ON DELETE CASCADE
);

-- 블로그의 받아 보는 사람 수, 새 글 소식 보내기
CREATE INDEX idx_blog_subscription_blog_id ON blog_subscription (blog_id);

COMMENT ON TABLE blog_subscription IS '원고 받아 보기 (블로그 구독)';
COMMENT ON COLUMN blog_subscription.email_enabled IS '새 원고를 메일로도 받기';

CREATE TABLE notification (
    notification_id BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    users_id        BIGINT       NOT NULL,
    kind            VARCHAR(10)  NOT NULL,
    post_id         BIGINT,
    post_title      VARCHAR(100) NOT NULL,
    actor_name      VARCHAR(30)  NOT NULL,
    read_at         TIMESTAMPTZ,
    created_at      TIMESTAMPTZ  NOT NULL,
    CONSTRAINT notification_pk PRIMARY KEY (notification_id),
    CONSTRAINT ck_notification_kind CHECK (kind IN ('post', 'comment')),
    CONSTRAINT fk_notification_users FOREIGN KEY (users_id) REFERENCES users (users_id) ON DELETE CASCADE,
    CONSTRAINT fk_notification_post FOREIGN KEY (post_id) REFERENCES post (post_id) ON DELETE SET NULL
);

-- 우편함 목록(최근 순), 안 읽은 수, 30일 정리
CREATE INDEX idx_notification_users_created ON notification (users_id, created_at DESC, notification_id DESC);
CREATE INDEX idx_notification_unread ON notification (users_id) WHERE read_at IS NULL;
CREATE INDEX idx_notification_created ON notification (created_at);
-- 같은 글의 새 글 소식은 한 사람에게 하나
CREATE UNIQUE INDEX uk_notification_post_once ON notification (users_id, post_id) WHERE kind = 'post';

COMMENT ON TABLE notification IS '우편함 소식';
COMMENT ON COLUMN notification.kind IS 'post(받아 보는 블로그의 새 글) · comment(내 글에 달린 댓글)';
COMMENT ON COLUMN notification.post_title IS '그때의 글 제목';
COMMENT ON COLUMN notification.actor_name IS '새 글이면 블로그 이름, 댓글이면 댓글 쓴 사람 닉네임';
