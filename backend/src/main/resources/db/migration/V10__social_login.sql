-- 소셜로만 가입한 회원은 비밀번호가 없다 (D-4). 이메일 로그인은 비밀번호가 없으면 늘 틀린 것으로 본다
ALTER TABLE users ALTER COLUMN password DROP NOT NULL;

-- 회원과 소셜 계정의 연결. 회사 토큰은 저장하지 않는다 (D-7)
--   (회사, 회사 쪽 회원 번호)는 회원 하나에만, (회원, 회사)는 하나만 (D-10)
--   탈퇴하면 탈퇴 트랜잭션이 이 회원의 줄을 지운다 (US5)
CREATE TABLE user_social_account (
    user_social_account_id BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    users_id               BIGINT       NOT NULL,
    provider               VARCHAR(20)  NOT NULL,
    provider_user_id       VARCHAR(100) NOT NULL,
    linked_at              TIMESTAMPTZ  NOT NULL,
    CONSTRAINT user_social_account_pk PRIMARY KEY (user_social_account_id),
    CONSTRAINT ck_user_social_account_provider CHECK (provider IN ('github', 'google', 'kakao', 'naver')),
    CONSTRAINT uq_user_social_account_provider_user UNIQUE (provider, provider_user_id),
    CONSTRAINT uq_user_social_account_users_provider UNIQUE (users_id, provider),
    CONSTRAINT fk_user_social_account_users FOREIGN KEY (users_id) REFERENCES users (users_id)
);

COMMENT ON TABLE user_social_account IS '소셜 계정 연결';
