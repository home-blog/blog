-- 개인 열쇠 (specs/020 data-model, ERD E-17): AI 비서(MCP 클라이언트)가 내 블로그에 붙는 열쇠.
--   열쇠 원문은 저장하지 않는다. SHA-256 해시(64자 16진수)와 화면에 보일 앞 8글자만 둔다.
--   scope: read(찾기·읽기) · draft(+ 임시 저장). 회원당 개수·기한은 설정 access-key.*로 서비스가 지킨다.
--   회원이 탈퇴하면 회원 모듈이 그 회원의 열쇠를 지운다(연쇄 삭제를 쓰지 않는 기존 규칙과 같다).

CREATE TABLE access_key (
    access_key_id BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    users_id      BIGINT       NOT NULL,
    name          VARCHAR(40)  NOT NULL,
    token_hash    CHAR(64)     NOT NULL,
    token_hint    VARCHAR(12)  NOT NULL,
    scope         VARCHAR(10)  NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL,
    expires_at    TIMESTAMPTZ  NOT NULL,
    last_used_at  TIMESTAMPTZ,
    CONSTRAINT access_key_pk PRIMARY KEY (access_key_id),
    CONSTRAINT fk_access_key_users FOREIGN KEY (users_id) REFERENCES users (users_id),
    CONSTRAINT uk_access_key_token UNIQUE (token_hash),
    CONSTRAINT ck_access_key_scope CHECK (scope IN ('read', 'draft')),
    CONSTRAINT ck_access_key_expires CHECK (expires_at > created_at)
);

CREATE INDEX idx_access_key_users ON access_key (users_id, created_at);

COMMENT ON TABLE access_key IS '개인 열쇠 (AI 비서 MCP 연결)';
COMMENT ON COLUMN access_key.token_hash IS '열쇠 원문의 SHA-256 (원문은 저장하지 않는다)';
COMMENT ON COLUMN access_key.token_hint IS '화면에 보일 앞 8글자';
COMMENT ON COLUMN access_key.scope IS 'read(찾기·읽기) · draft(+ 임시 저장)';
