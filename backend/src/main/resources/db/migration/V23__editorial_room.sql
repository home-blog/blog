-- 편집실 (관리자 화면, specs/018 data-model, ERD E-15).
--   post.locked_at·lock_reason: 편집실이 내린 글. 비공개로 돌리고 잠가, 주인은 다시 공개로 바꿀 수 없다(고치기는 된다).
--   post_report.resolved_at·resolution: 신고를 닫은 시각과 결과(taken_down 내림 · dismissed 반려). 비어 있으면 검토 대기.
--   board_report: 글마당 글 신고(블로그 글 신고와 같은 칸, 한 사람·한 글 한 번). 글을 지우면 함께 지운다.
--   editorial_action: 처리 기록. 글이 지워져도 그때의 제목은 남는다(대상 번호만 비움).
--   notification.kind에 editorial(편집실 소식)을 더한다.

ALTER TABLE post ADD COLUMN locked_at TIMESTAMPTZ;
ALTER TABLE post ADD COLUMN lock_reason VARCHAR(200);
COMMENT ON COLUMN post.locked_at IS '편집실이 내린 시각 (비어 있지 않으면 주인이 공개로 바꿀 수 없다)';
COMMENT ON COLUMN post.lock_reason IS '편집실이 적은 내림 사유';

ALTER TABLE post_report ADD COLUMN resolved_at TIMESTAMPTZ;
ALTER TABLE post_report ADD COLUMN resolution VARCHAR(20);
ALTER TABLE post_report ADD CONSTRAINT ck_post_report_resolution CHECK (
    (resolved_at IS NULL AND resolution IS NULL)
    OR (resolved_at IS NOT NULL AND resolution IN ('taken_down', 'dismissed'))
);
-- 검토 대기 묶음
CREATE INDEX idx_post_report_pending ON post_report (post_id) WHERE resolved_at IS NULL;

CREATE TABLE board_report (
    board_report_id BIGINT      NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    users_id        BIGINT      NOT NULL,
    board_post_id   BIGINT      NOT NULL,
    reason          VARCHAR(20) NOT NULL,
    detail          VARCHAR(200),
    created_at      TIMESTAMPTZ NOT NULL,
    resolved_at     TIMESTAMPTZ,
    resolution      VARCHAR(20),
    CONSTRAINT board_report_pk PRIMARY KEY (board_report_id),
    CONSTRAINT uk_board_report_users_post UNIQUE (users_id, board_post_id),
    CONSTRAINT ck_board_report_reason CHECK (reason IN ('SPAM', 'ABUSE', 'ADULT', 'OTHER')),
    CONSTRAINT ck_board_report_resolution CHECK (
        (resolved_at IS NULL AND resolution IS NULL)
        OR (resolved_at IS NOT NULL AND resolution = 'dismissed')
    ),
    CONSTRAINT fk_board_report_users FOREIGN KEY (users_id) REFERENCES users (users_id) ON DELETE CASCADE,
    CONSTRAINT fk_board_report_post FOREIGN KEY (board_post_id) REFERENCES board_post (board_post_id) ON DELETE CASCADE
);
CREATE INDEX idx_board_report_pending ON board_report (board_post_id) WHERE resolved_at IS NULL;
COMMENT ON TABLE board_report IS '글마당 글 신고';

CREATE TABLE editorial_action (
    editorial_action_id BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    target_kind         VARCHAR(10)  NOT NULL,
    post_id             BIGINT,
    board_post_id       BIGINT,
    target_title        VARCHAR(100) NOT NULL,
    action              VARCHAR(20)  NOT NULL,
    reason              VARCHAR(200),
    report_count        INT          NOT NULL DEFAULT 0,
    users_id            BIGINT,
    created_at          TIMESTAMPTZ  NOT NULL,
    CONSTRAINT editorial_action_pk PRIMARY KEY (editorial_action_id),
    CONSTRAINT ck_editorial_action_target CHECK (target_kind IN ('post', 'board')),
    CONSTRAINT ck_editorial_action_action CHECK (action IN ('taken_down', 'dismissed', 'removed', 'unlocked')),
    CONSTRAINT fk_editorial_action_post FOREIGN KEY (post_id) REFERENCES post (post_id) ON DELETE SET NULL,
    CONSTRAINT fk_editorial_action_board_post FOREIGN KEY (board_post_id) REFERENCES board_post (board_post_id) ON DELETE SET NULL,
    CONSTRAINT fk_editorial_action_users FOREIGN KEY (users_id) REFERENCES users (users_id) ON DELETE SET NULL
);
CREATE INDEX idx_editorial_action_created ON editorial_action (created_at DESC, editorial_action_id DESC);
COMMENT ON TABLE editorial_action IS '편집실 처리 기록';

ALTER TABLE notification DROP CONSTRAINT ck_notification_kind;
ALTER TABLE notification ADD CONSTRAINT ck_notification_kind
    CHECK (kind IN ('post', 'comment', 'board', 'accepted', 'editorial'));
COMMENT ON COLUMN notification.kind IS 'post(받아 보는 블로그의 새 글) · comment(내 글에 달린 댓글) · board(내 글마당 글에 달린 댓글) · accepted(내 글마당 댓글이 채택됨) · editorial(편집실이 내 글을 내리거나 지움)';
ALTER TABLE notification ADD COLUMN note VARCHAR(200);
COMMENT ON COLUMN notification.note IS '편집실 소식의 사유 (다른 소식은 비어 있다)';
