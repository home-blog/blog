-- 운영 강화 (specs/022 data-model, ERD E-19): 댓글 신고·자동 가림·회원 정지.
--   comment_report: 블로그 글 댓글 신고(글 신고와 같은 칸, 한 사람·한 댓글 한 번). 댓글을 지우면 함께 지운다.
--   comment.hidden_at·hidden_by: 편집실이 가린 댓글(auto = 신고가 모여 저절로, editor = 관리자). 줄은 남고 목록에서 내용을 뺀다.
--   users.suspended_until·suspend_reason: 이 시각 전까지 정지(로그인 못 함). 시각이 지나면 저절로 풀린다.
--   editorial_action: 대상 comment·member, 처리 hidden·restored·suspended·unsuspended.

CREATE TABLE comment_report (
    comment_report_id BIGINT      NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    users_id          BIGINT      NOT NULL,
    comment_id        BIGINT      NOT NULL,
    reason            VARCHAR(20) NOT NULL,
    detail            VARCHAR(200),
    created_at        TIMESTAMPTZ NOT NULL,
    resolved_at       TIMESTAMPTZ,
    resolution        VARCHAR(20),
    CONSTRAINT comment_report_pk PRIMARY KEY (comment_report_id),
    CONSTRAINT uk_comment_report_users_comment UNIQUE (users_id, comment_id),
    CONSTRAINT ck_comment_report_reason CHECK (reason IN ('SPAM', 'ABUSE', 'ADULT', 'OTHER')),
    CONSTRAINT ck_comment_report_resolution CHECK (
        (resolved_at IS NULL AND resolution IS NULL)
        OR (resolved_at IS NOT NULL AND resolution IN ('hidden', 'dismissed'))
    ),
    CONSTRAINT fk_comment_report_users FOREIGN KEY (users_id) REFERENCES users (users_id) ON DELETE CASCADE,
    CONSTRAINT fk_comment_report_comment FOREIGN KEY (comment_id) REFERENCES comment (comment_id) ON DELETE CASCADE
);
CREATE INDEX idx_comment_report_pending ON comment_report (comment_id) WHERE resolved_at IS NULL;
COMMENT ON TABLE comment_report IS '블로그 글 댓글 신고';

ALTER TABLE comment ADD COLUMN hidden_at TIMESTAMPTZ;
ALTER TABLE comment ADD COLUMN hidden_by VARCHAR(10);
ALTER TABLE comment ADD CONSTRAINT ck_comment_hidden CHECK (
    (hidden_at IS NULL AND hidden_by IS NULL)
    OR (hidden_at IS NOT NULL AND hidden_by IN ('auto', 'editor'))
);
COMMENT ON COLUMN comment.hidden_at IS '편집실이 가린 시각 (목록에서 내용·쓴 사람을 뺀다)';
COMMENT ON COLUMN comment.hidden_by IS 'auto(신고가 모여 저절로) · editor(관리자)';

ALTER TABLE users ADD COLUMN suspended_until TIMESTAMPTZ;
ALTER TABLE users ADD COLUMN suspend_reason VARCHAR(200);
COMMENT ON COLUMN users.suspended_until IS '이 시각 전까지 이용 정지 (지나면 저절로 풀린다)';
COMMENT ON COLUMN users.suspend_reason IS '정지 사유';

ALTER TABLE editorial_action ADD COLUMN comment_id BIGINT;
ALTER TABLE editorial_action ADD COLUMN member_id BIGINT;
ALTER TABLE editorial_action ADD CONSTRAINT fk_editorial_action_comment
    FOREIGN KEY (comment_id) REFERENCES comment (comment_id) ON DELETE SET NULL;
ALTER TABLE editorial_action ADD CONSTRAINT fk_editorial_action_member
    FOREIGN KEY (member_id) REFERENCES users (users_id) ON DELETE SET NULL;
ALTER TABLE editorial_action DROP CONSTRAINT ck_editorial_action_target;
ALTER TABLE editorial_action ADD CONSTRAINT ck_editorial_action_target
    CHECK (target_kind IN ('post', 'board', 'comment', 'member'));
ALTER TABLE editorial_action DROP CONSTRAINT ck_editorial_action_action;
ALTER TABLE editorial_action ADD CONSTRAINT ck_editorial_action_action
    CHECK (action IN ('taken_down', 'dismissed', 'removed', 'unlocked', 'hidden', 'restored', 'suspended', 'unsuspended'));
COMMENT ON COLUMN editorial_action.comment_id IS '가린·반려한 댓글 (지우면 비움)';
COMMENT ON COLUMN editorial_action.member_id IS '정지하거나 푼 회원';
