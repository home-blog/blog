-- 방명록 (엽서함, specs/021 data-model, ERD E-18).
--   guestbook_entry: 블로그에 들른 회원이 남기는 엽서. 우표 다섯 가지, 비밀 엽서(쓴 사람·주인만 읽음), 주인의 답장 하나.
--   블로그가 닫히면(탈퇴) 함께 지운다. 쓴 사람은 탈퇴해도 줄이 남는다(soft delete) → "탈퇴한 회원".
--   notification.kind에 guestbook(내 방명록에 새 엽서) · gb_reply(내 엽서에 답장)를 더한다.
--   notification.guestbook_entry_id: 엽서를 지우면 소식도 지운다. notification.blog_id: 방명록 주소를 만든다.

CREATE TABLE guestbook_entry (
    guestbook_entry_id BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    blog_id            BIGINT       NOT NULL,
    users_id           BIGINT       NOT NULL,
    body               VARCHAR(300) NOT NULL,
    stamp              VARCHAR(10)  NOT NULL,
    is_secret          BOOLEAN      NOT NULL DEFAULT false,
    reply              VARCHAR(300),
    replied_at         TIMESTAMPTZ,
    created_at         TIMESTAMPTZ  NOT NULL,
    CONSTRAINT guestbook_entry_pk PRIMARY KEY (guestbook_entry_id),
    CONSTRAINT ck_guestbook_entry_stamp CHECK (stamp IN ('pine', 'wave', 'moon', 'plum', 'crane')),
    CONSTRAINT ck_guestbook_entry_reply CHECK ((reply IS NULL AND replied_at IS NULL)
        OR (reply IS NOT NULL AND replied_at IS NOT NULL)),
    CONSTRAINT fk_guestbook_entry_blog FOREIGN KEY (blog_id) REFERENCES blog (blog_id) ON DELETE CASCADE,
    CONSTRAINT fk_guestbook_entry_users FOREIGN KEY (users_id) REFERENCES users (users_id) ON DELETE CASCADE
);

-- 방명록 목록(최근 순), 같은 회원의 마지막 엽서·오늘 엽서 수
CREATE INDEX idx_guestbook_entry_blog_created ON guestbook_entry (blog_id, created_at DESC, guestbook_entry_id DESC);
CREATE INDEX idx_guestbook_entry_users_created ON guestbook_entry (users_id, created_at DESC);

COMMENT ON TABLE guestbook_entry IS '방명록 엽서';
COMMENT ON COLUMN guestbook_entry.stamp IS '우표: pine(소나무) · wave(파도) · moon(달) · plum(매화) · crane(학)';
COMMENT ON COLUMN guestbook_entry.is_secret IS '비밀 엽서: 쓴 사람과 블로그 주인만 읽는다';
COMMENT ON COLUMN guestbook_entry.reply IS '블로그 주인의 답장 (하나)';
COMMENT ON COLUMN guestbook_entry.replied_at IS '답장을 처음 쓴 시각';

ALTER TABLE notification ADD COLUMN guestbook_entry_id BIGINT;
ALTER TABLE notification ADD COLUMN blog_id BIGINT;
ALTER TABLE notification ADD CONSTRAINT fk_notification_guestbook_entry
    FOREIGN KEY (guestbook_entry_id) REFERENCES guestbook_entry (guestbook_entry_id) ON DELETE CASCADE;
ALTER TABLE notification ADD CONSTRAINT fk_notification_blog
    FOREIGN KEY (blog_id) REFERENCES blog (blog_id) ON DELETE CASCADE;
COMMENT ON COLUMN notification.guestbook_entry_id IS '방명록 소식의 엽서 (엽서를 지우면 소식도 지운다)';
COMMENT ON COLUMN notification.blog_id IS '방명록 소식의 블로그';

ALTER TABLE notification DROP CONSTRAINT ck_notification_kind;
ALTER TABLE notification ADD CONSTRAINT ck_notification_kind
    CHECK (kind IN ('post', 'comment', 'board', 'accepted', 'editorial', 'reply', 'guestbook', 'gb_reply'));
COMMENT ON COLUMN notification.kind IS 'post(받아 보는 블로그의 새 글) · comment(내 글에 달린 댓글) · board(내 글마당 글에 달린 댓글) · accepted(내 글마당 댓글이 채택됨) · editorial(편집실이 내 글을 내리거나 지움) · reply(내 댓글에 답글) · guestbook(내 방명록에 새 엽서) · gb_reply(내 엽서에 답장)';
