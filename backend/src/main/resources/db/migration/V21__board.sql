-- 글마당 (커뮤니티, specs/017 data-model, ERD E-14).
--   board_post: 블로그와 따로 서는 게시판 글. 주제는 블로그 글과 같은 topic 표, 종류는 이야기(talk)·물음(question).
--   board_comment: 글마당 글의 댓글. 글을 지우면 함께 지운다.
--   물음을 쓴 사람이 고른 댓글은 board_post.accepted_comment_id (글 하나에 하나, 채택 도장).
-- 탈퇴한 회원의 글·댓글은 남긴다(회원 줄이 남는 soft delete). 이름은 화면에서 "탈퇴한 회원". 회원 줄을 실제로 지우는 일은
-- 서비스에 없지만 016과 같이 연쇄 삭제를 걸어 둔다.
-- notification(016)에 글마당 소식 두 가지와 글마당 글 번호 칸을 더한다.

CREATE TABLE board_post (
    board_post_id       BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    users_id            BIGINT       NOT NULL,
    topic_id            BIGINT       NOT NULL,
    kind                VARCHAR(10)  NOT NULL,
    title               VARCHAR(100) NOT NULL,
    content             TEXT         NOT NULL,
    views               BIGINT       NOT NULL DEFAULT 0,
    comment_count       INT          NOT NULL DEFAULT 0,
    accepted_comment_id BIGINT,
    created_at          TIMESTAMPTZ  NOT NULL,
    updated_at          TIMESTAMPTZ  NOT NULL,
    CONSTRAINT board_post_pk PRIMARY KEY (board_post_id),
    CONSTRAINT ck_board_post_kind CHECK (kind IN ('talk', 'question')),
    CONSTRAINT ck_board_post_counts CHECK (views >= 0 AND comment_count >= 0),
    CONSTRAINT fk_board_post_users FOREIGN KEY (users_id) REFERENCES users (users_id) ON DELETE CASCADE,
    CONSTRAINT fk_board_post_topic FOREIGN KEY (topic_id) REFERENCES topic (topic_id)
);

CREATE TABLE board_comment (
    board_comment_id BIGINT        NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    board_post_id    BIGINT        NOT NULL,
    users_id         BIGINT        NOT NULL,
    content          VARCHAR(1000) NOT NULL,
    created_at       TIMESTAMPTZ   NOT NULL,
    CONSTRAINT board_comment_pk PRIMARY KEY (board_comment_id),
    CONSTRAINT fk_board_comment_post FOREIGN KEY (board_post_id) REFERENCES board_post (board_post_id) ON DELETE CASCADE,
    CONSTRAINT fk_board_comment_users FOREIGN KEY (users_id) REFERENCES users (users_id) ON DELETE CASCADE
);

ALTER TABLE board_post ADD CONSTRAINT fk_board_post_accepted
    FOREIGN KEY (accepted_comment_id) REFERENCES board_comment (board_comment_id) ON DELETE SET NULL;

-- 목록(최신순, 주제별), 내 마지막 글(너무 빨리 올리기), 댓글 목록, 내 마지막 댓글
CREATE INDEX idx_board_post_created ON board_post (created_at DESC, board_post_id DESC);
CREATE INDEX idx_board_post_topic_created ON board_post (topic_id, created_at DESC, board_post_id DESC);
CREATE INDEX idx_board_post_users ON board_post (users_id, created_at DESC);
CREATE INDEX idx_board_comment_post ON board_comment (board_post_id, created_at, board_comment_id);
CREATE INDEX idx_board_comment_users ON board_comment (users_id, created_at DESC);

COMMENT ON TABLE board_post IS '글마당 글 (커뮤니티)';
COMMENT ON COLUMN board_post.kind IS 'talk(이야기) · question(물음)';
COMMENT ON COLUMN board_post.accepted_comment_id IS '물음을 쓴 사람이 채택한 댓글';
COMMENT ON TABLE board_comment IS '글마당 댓글';

-- 우편함: board(내 글마당 글에 댓글) · accepted(내 댓글이 채택됨)
ALTER TABLE notification DROP CONSTRAINT ck_notification_kind;
ALTER TABLE notification ADD CONSTRAINT ck_notification_kind CHECK (kind IN ('post', 'comment', 'board', 'accepted'));
ALTER TABLE notification ADD COLUMN board_post_id BIGINT;
ALTER TABLE notification ADD CONSTRAINT fk_notification_board_post
    FOREIGN KEY (board_post_id) REFERENCES board_post (board_post_id) ON DELETE SET NULL;
COMMENT ON COLUMN notification.kind IS 'post(받아 보는 블로그의 새 글) · comment(내 글에 달린 댓글) · board(내 글마당 글에 달린 댓글) · accepted(내 글마당 댓글이 채택됨)';
COMMENT ON COLUMN notification.board_post_id IS '글마당 소식의 글 (블로그 글 소식은 post_id)';
