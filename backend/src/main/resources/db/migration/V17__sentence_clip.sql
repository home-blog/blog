-- 문장 수집과 필사 노트 (specs/015 US3, data-model, ERD E-12).
--   글 본문에서 고른 문장을 모은 사람의 필사 노트에 옮겨 적는다. 필사 노트는 모은 사람만 본다.
--   원문 글이 지워져도 문장은 남는다: post_id를 비우고(ON DELETE SET NULL), 모을 때의 글 제목·블로그 이름을 같이 적어 둔다.
--   탈퇴하면 community 모듈이 MemberWithdrawnEvent로 지운다(회원 줄은 남는 soft delete라 연쇄 삭제는 테스트 정리용이다).
--   같은 사람·같은 글·같은 문장은 하나: 다시 모으면 서버가 INSERT … ON CONFLICT DO NOTHING으로 앞의 것을 돌려준다.

CREATE TABLE sentence_clip (
    sentence_clip_id BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    users_id         BIGINT       NOT NULL,
    post_id          BIGINT,
    post_title       VARCHAR(100) NOT NULL,
    blog_name        VARCHAR(30)  NOT NULL,
    text             VARCHAR(300) NOT NULL,
    created_at       TIMESTAMPTZ  NOT NULL,
    CONSTRAINT sentence_clip_pk PRIMARY KEY (sentence_clip_id),
    CONSTRAINT uk_sentence_clip_users_post_text UNIQUE (users_id, post_id, text),
    CONSTRAINT fk_sentence_clip_users FOREIGN KEY (users_id) REFERENCES users (users_id) ON DELETE CASCADE,
    CONSTRAINT fk_sentence_clip_post FOREIGN KEY (post_id) REFERENCES post (post_id) ON DELETE SET NULL
);

-- 필사 노트 목록(최근 순)과 한 사람이 모은 수
CREATE INDEX idx_sentence_clip_users_created ON sentence_clip (users_id, created_at DESC, sentence_clip_id DESC);
-- 글마다 모은 사람 수, 글이 지워질 때 비우기
CREATE INDEX idx_sentence_clip_post_id ON sentence_clip (post_id);

COMMENT ON TABLE sentence_clip IS '문장 수집 (필사 노트)';
COMMENT ON COLUMN sentence_clip.post_id IS '원문 글. 지워지면 비운다';
COMMENT ON COLUMN sentence_clip.post_title IS '모을 때의 글 제목';
COMMENT ON COLUMN sentence_clip.blog_name IS '모을 때의 블로그 이름';
COMMENT ON COLUMN sentence_clip.text IS '모은 문장 (앞뒤 공백을 지우고 공백을 한 칸으로)';
