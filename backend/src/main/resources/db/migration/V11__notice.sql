-- 공지사항 (specs/012 data-model, ERD-변경-요청.md E-9)
-- 관리자는 회원 표의 역할 칸으로 정한다 (D-1). 관리자 지정은 운영자가 DB에서 한 번 (D-3)

ALTER TABLE users ADD COLUMN role VARCHAR(10) NOT NULL DEFAULT 'member';
ALTER TABLE users ADD CONSTRAINT ck_users_role CHECK (role IN ('member', 'admin'));

CREATE TABLE notice (
    notice_id       BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    kind            VARCHAR(10)  NOT NULL,
    title           VARCHAR(100) NOT NULL,
    content         TEXT         NOT NULL,
    release_version VARCHAR(20),
    pinned          BOOLEAN      NOT NULL DEFAULT false,
    users_id        BIGINT       NOT NULL,
    created_at      TIMESTAMPTZ  NOT NULL,
    updated_at      TIMESTAMPTZ,
    CONSTRAINT notice_pk PRIMARY KEY (notice_id),
    CONSTRAINT ck_notice_kind CHECK (kind IN ('update', 'notice')),
    -- 업데이트에만 릴리스 번호가 있다 (D-5, D-6)
    CONSTRAINT ck_notice_release_version CHECK (
        (kind = 'update' AND release_version ~ '^[0-9]{1,4}\.[0-9]{1,4}\.[0-9]{1,4}$')
        OR (kind = 'notice' AND release_version IS NULL)
    ),
    CONSTRAINT fk_notice_users FOREIGN KEY (users_id) REFERENCES users (users_id)
);

-- 탭별 목록: 고정 먼저, 그 안에서 새 글 먼저 (D-7)
CREATE INDEX idx_notice_list ON notice (kind, pinned DESC, created_at DESC);
CREATE INDEX idx_notice_order ON notice (pinned DESC, created_at DESC);

COMMENT ON COLUMN users.role IS '역할 (member, admin)';
COMMENT ON TABLE notice IS '공지사항';
